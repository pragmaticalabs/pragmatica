import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

/// Pins the gate's corpus: [ReactorRoots] follows aggregator poms into their children, so a config
/// accessor read only from `environment/*`, `resource/*`, `forge/*` or `pg-tools/*` is live, not a
/// false-DEAD that tempts an `@ConfigKeyLive` suppression.
///
/// The real-tree tests read the poms with a DOM parser — a second reader that shares nothing with
/// [ReactorRoots]' text scan — so a bug in the scan cannot also be a bug in its own oracle. The
/// fixture tests build a throwaway `aether/`-shaped tree (aggregator, nested leaf, profile-gated leaf)
/// with generated bytecode, so the control needs no change to a real module.
class ReactorRootsTest {
    private static final String POM_OPEN = "<project xmlns=\"http://maven.apache.org/POM/4.0.0\">";

    // --- the real tree --------------------------------------------------------------------------------

    /// Floors, not exact counts: a module added to the tree must not redden this test (the gate pom test
    /// keeps the pom in sync). 56 = every non-aggregator module reachable through `<modules>` outside profiles: the 28 direct
    /// leaves of `aether/pom.xml` (incl. this gate; the dashboard module was the 29th until it was removed) + environment 5 + resource 13 + forge 4 + pg-tools 6.
    /// 55 of them are `packaging=jar`; `pg-tools/pg-maven-plugin` is `maven-plugin`. The
    /// exact set is compared to the DOM reading above; the floors catch a collapse.
    @Test
    void declaredModules_realTree_isEveryNonAggregatorModuleReachableThroughModules() throws Exception {
        var expected = reachableLeafModules(ReactorRoots.aetherRoot());
        var actual = ReactorRoots.declaredModules();

        assertEquals(expected, Set.copyOf(actual), "ReactorRoots disagrees with the DOM reading of the module tree");
        assertEquals(actual.size(), Set.copyOf(actual).size(), "a module is listed twice: " + actual);
        assertTrue(actual.size() >= 56, "corpus collapsed below its floor of 56: " + actual.size());
        assertTrue(actual.stream().filter(module -> "jar".equals(packaging(module))).count() >= 55,
                   "packaging=jar modules collapsed below their floor of 55");
    }

    @Test
    void declaredModules_realTree_includesNestedModulesOfEveryAggregator() {
        var relative = ReactorRoots.declaredModules().stream()
                                   .map(module -> ReactorRoots.aetherRoot().relativize(module).toString())
                                   .toList();

        assertTrue(relative.containsAll(List.of("environment/hetzner",
                                                "environment/aws",
                                                "resource/db-jooq",
                                                "resource/api",
                                                "resource/services/artifact-repo",
                                                "forge/forge-core",
                                                "pg-tools/pg-parser",
                                                "pg-tools/pg-maven-plugin")),
                   "nested aggregator children missing from the corpus: " + relative);
    }

    @Test
    void declaredModules_realTree_excludesAggregatorsAndProfileGatedModules() {
        var relative = ReactorRoots.declaredModules().stream()
                                   .map(module -> ReactorRoots.aetherRoot().relativize(module).toString())
                                   .toList();

        for (var notCorpus : List.of("environment", "resource", "resource/services", "forge", "pg-tools",
                                     "e2e-tests", "cloud-tests", "forge/forge-tests")) {
            assertFalse(relative.contains(notCorpus), notCorpus + " must not be a corpus module: " + relative);
        }
    }

    /// The non-vacuity guard: every corpus module with production sources is BUILT (has
    /// `target/classes` holding at least one class) by the time the gate runs, and contributes a root (resources-only
    /// `pg-test-corpus` also has one, so roots may outnumber source modules). Nested modules are built
    /// before the gate only because the gate's pom depends on them — see the next test.
    @Test
    void productionRoots_realTree_hasOneRootPerModuleWithSources() {
        var withSources = ReactorRoots.declaredModules().stream()
                                      .filter(module -> Files.isDirectory(module.resolve("src/main/java")))
                                      .toList();

        assertTrue(ReactorRoots.missingProductionOutput().isEmpty(),
                   "corpus modules with sources but no target/classes: " + ReactorRoots.missingProductionOutput());
        assertTrue(withSources.size() >= 54, "modules with src/main/java collapsed below their floor of 54");
        assertTrue(ReactorRoots.productionRoots().containsAll(withSources.stream().map(module -> module.resolve("target/classes")).toList()),
                   "a module with sources contributes no root");

        var empty = withSources.stream()
                               .map(module -> module.resolve("target/classes"))
                               .filter(ReactorRootsTest::holdsNoClassFile)
                               .toList();

        assertTrue(empty.isEmpty(), "corpus modules whose target/classes holds no .class file: " + empty);
    }

    /// An existing but empty `target/classes` (a CI job that created the directory and compiled nothing into it) would
    /// pass the existence check above and still scan nothing.
    private static boolean holdsNoClassFile(Path root) {
        try (var files = Files.walk(root)) {
            return files.noneMatch(file -> file.toString().endsWith(".class"));
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    /// Reactor order by construction: Maven schedules this gate after every module it declares as a
    /// dependency, so a corpus module missing from the gate pom could be built AFTER the gate and the
    /// gate would scan a smaller corpus (or fail only on machines that built it late).
    @Test
    void gatePom_declaresEveryCorpusModuleAsADependency() throws Exception {
        var declared = dependencyArtifactIds(ReactorRoots.aetherRoot().resolve("dead-surface-gate/pom.xml"));
        var undeclared = new ArrayList<String>();

        for (var module : ReactorRoots.declaredModules()) {
            var artifactId = artifactId(module);

            if (!artifactId.equals("dead-surface-gate") && !declared.contains(artifactId)) {
                undeclared.add(artifactId);
            }
        }

        assertTrue(undeclared.isEmpty(),
                   "corpus modules the gate pom does not depend on (add them, test scope): " + undeclared);
    }

    // --- fixture tree: CONTROL ------------------------------------------------------------------------

    /// CONTROL for the whole change. The accessor is read ONLY by a class in a leaf nested under an
    /// aggregator; the scan sees only the fixture tree, so liveness can come from nowhere else. Before
    /// the fix `declaredModules` stopped at the aggregator, the corpus was empty and this was DEAD.
    @Test
    void accessorReadOnlyInNestedModule_isLive(@TempDir Path aether) throws IOException {
        var accessor = firstAccessor();

        fixtureTree(aether);
        writeReader(aether.resolve("agg/leaf/target/classes"), accessor);

        var reachability = BytecodeReachability.scan(ReactorRoots.productionRoots(aether));

        assertEquals(List.of(aether.resolve("agg/leaf")), ReactorRoots.declaredModules(aether));
        assertTrue(reachability.isReachable(MethodRef.of(accessor)),
                   "an accessor read only from a module nested under an aggregator must be live");
    }

    /// The same reader in a profile-gated leaf is NOT in the corpus: negative control, same instrument.
    @Test
    void accessorReadOnlyInProfileGatedModule_isDead(@TempDir Path aether) throws IOException {
        var accessor = firstAccessor();

        fixtureTree(aether);
        writeReader(aether.resolve("agg/gated/target/classes"), accessor);

        var reachability = BytecodeReachability.scan(ReactorRoots.productionRoots(aether));

        assertEquals(List.of(aether.resolve("agg/leaf")), ReactorRoots.declaredModules(aether));
        assertFalse(reachability.isReachable(MethodRef.of(accessor)),
                    "a profile-gated module is not built by the default reactor and must not feed the corpus");
    }

    @Test
    void missingProductionOutput_unbuiltNestedModule_isReported(@TempDir Path aether) throws IOException {
        fixtureTree(aether);
        Files.createDirectories(aether.resolve("agg/leaf/src/main/java"));

        assertEquals(List.of(aether.resolve("agg/leaf")), ReactorRoots.missingProductionOutput(aether));
        assertEquals(List.of(), ReactorRoots.productionRoots(aether), "no output means no root, never a silent pass");
    }

    @Test
    void declaredModules_moduleWithoutPom_failsLoudly(@TempDir Path aether) throws IOException {
        Files.writeString(aether.resolve("pom.xml"),
                          POM_OPEN + "<modules><module>ghost</module></modules></project>");

        var thrown = assertThrows(IllegalStateException.class, () -> ReactorRoots.declaredModules(aether));

        assertTrue(thrown.getMessage().contains("ghost"), thrown.getMessage());
    }

    @Test
    void declaredModules_rootWithoutModulesBlock_failsLoudly(@TempDir Path aether) throws IOException {
        Files.writeString(aether.resolve("pom.xml"), POM_OPEN + "</project>");

        var thrown = assertThrows(IllegalStateException.class, () -> ReactorRoots.declaredModules(aether));

        assertTrue(thrown.getMessage().contains("No <modules> block"), thrown.getMessage());
    }

    // --- helpers --------------------------------------------------------------------------------------

    /// `aether/pom.xml` -> aggregator `agg` -> `leaf`; the aggregator also lists `gated` inside a
    /// `<profile>`, declared BEFORE the default `<modules>` so a reader that takes the first block it finds
    /// picks the profile's.
    private static void fixtureTree(Path aether) throws IOException {
        Files.writeString(aether.resolve("pom.xml"),
                          POM_OPEN + "<modules><module>agg</module><!-- <module>commented</module> --></modules></project>");
        Files.createDirectories(aether.resolve("agg/leaf"));
        Files.createDirectories(aether.resolve("agg/gated"));
        Files.writeString(aether.resolve("agg/pom.xml"),
                          POM_OPEN + "<packaging>pom</packaging>" +
                          "<profiles><profile><id>gated</id><modules><module>gated</module></modules></profile>" +
                          "</profiles><modules><module> leaf </module></modules></project>");
        Files.writeString(aether.resolve("agg/leaf/pom.xml"), POM_OPEN + "</project>");
        Files.writeString(aether.resolve("agg/gated/pom.xml"), POM_OPEN + "</project>");
    }

    private static Method firstAccessor() {
        return ClusterBootstrapConfig.class.getRecordComponents()[0].getAccessor();
    }

    /// Generates `Reader` with one static method that calls `accessor` on a `ClusterBootstrapConfig`
    /// argument — a caller outside the declaring class, which is all [BytecodeReachability] counts.
    private static void writeReader(Path classesDir, Method accessor) throws IOException {
        var writer = new ClassWriter(ClassWriter.COMPUTE_MAXS);
        var owner = Type.getInternalName(accessor.getDeclaringClass());
        var descriptor = Type.getMethodDescriptor(accessor);

        writer.visit(Opcodes.V17, Opcodes.ACC_PUBLIC, "fixture/Reader", null, "java/lang/Object", null);

        var method = writer.visitMethod(Opcodes.ACC_PUBLIC | Opcodes.ACC_STATIC, "read",
                                        "(L" + owner + ";)V", null, null);

        method.visitCode();
        method.visitVarInsn(Opcodes.ALOAD, 0);
        method.visitMethodInsn(Opcodes.INVOKEVIRTUAL, owner, accessor.getName(), descriptor, false);
        method.visitInsn(Type.getReturnType(accessor).getSize() == 2 ? Opcodes.POP2 : Opcodes.POP);
        method.visitInsn(Opcodes.RETURN);
        method.visitMaxs(0, 0);
        method.visitEnd();
        writer.visitEnd();

        var target = classesDir.resolve("fixture/Reader.class");

        Files.createDirectories(target.getParent());
        Files.write(target, writer.toByteArray());
    }

    // --- the DOM oracle: shares no code with ReactorRoots ---------------------------------------------

    private static Set<Path> reachableLeafModules(Path directory) throws Exception {
        var leaves = new HashSet<Path>();

        for (var name : directModules(directory)) {
            var module = directory.resolve(name);

            if (directModules(module).isEmpty()) {
                leaves.add(module);
            } else {
                leaves.addAll(reachableLeafModules(module));
            }
        }

        return leaves;
    }

    /// `<project><modules><module>` children only — `<profiles>` are a different branch of the tree.
    private static List<String> directModules(Path directory) throws Exception {
        var modules = new ArrayList<String>();
        var project = parse(directory.resolve("pom.xml")).getDocumentElement();

        for (var child : children(project, "modules")) {
            for (var module : children(child, "module")) {
                modules.add(module.getTextContent().trim());
            }
        }

        return modules;
    }

    private static String packaging(Path module) {
        try {
            return children(parse(module.resolve("pom.xml")).getDocumentElement(), "packaging").stream()
                                                                                                .map(Node::getTextContent)
                                                                                                .map(String::trim)
                                                                                                .findFirst()
                                                                                                .orElse("jar");
        } catch (Exception e) {
            throw new IllegalStateException(e);
        }
    }

    private static String artifactId(Path module) {
        try {
            return children(parse(module.resolve("pom.xml")).getDocumentElement(), "artifactId").getFirst()
                                                                                               .getTextContent()
                                                                                               .trim();
        } catch (Exception e) {
            throw new IllegalStateException(e);
        }
    }

    private static Set<String> dependencyArtifactIds(Path pom) throws Exception {
        var ids = new HashSet<String>();

        for (var dependencies : children(parse(pom).getDocumentElement(), "dependencies")) {
            for (var dependency : children(dependencies, "dependency")) {
                children(dependency, "artifactId").forEach(id -> ids.add(id.getTextContent().trim()));
            }
        }

        return ids;
    }

    private static Document parse(Path pom) throws Exception {
        var factory = DocumentBuilderFactory.newInstance();

        factory.setNamespaceAware(false);
        return factory.newDocumentBuilder().parse(pom.toFile());
    }

    private static List<Element> children(Element parent, String tag) {
        var result = new ArrayList<Element>();

        for (Node node = parent.getFirstChild(); node != null; node = node.getNextSibling()) {
            if (node instanceof Element element && element.getTagName().equals(tag)) {
                result.add(element);
            }
        }

        return result;
    }
}
