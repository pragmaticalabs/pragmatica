def render(text, values):
    for key, value in values.items():
        text = text.replace("@" + key + "@", str(value))
    return text


def write(path, content):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(content)


AGGREGATOR = """<?xml version="1.0" encoding="UTF-8"?>
<project xmlns="http://maven.apache.org/POM/4.0.0" xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xsi:schemaLocation="http://maven.apache.org/POM/4.0.0 http://maven.apache.org/xsd/maven-4.0.0.xsd">
    <modelVersion>4.0.0</modelVersion>
    <groupId>org.pragmatica.aether.test</groupId>
    <artifactId>test-stream-ckpt-all</artifactId>
    <version>1.0.0</version>
    <packaging>pom</packaging>
    <name>Test Blueprint - Stream checkpoint load, all arms</name>
    <modules>
@MODULES@
    </modules>
</project>
"""

ARMS = [(g, p) for g in (1, 10, 100) for p in (4, 16)]


def main():
    if sys.argv[1] == "all":
        out = sys.argv[2]
        for g, p in ARMS:
            generate(g, p, os.path.join(out, "g%d-p%d" % (g, p)))
        write(os.path.join(out, "pom.xml"), AGGREGATOR.replace("@MODULES@", "\n".join("        <module>g%d-p%d</module>" % arm for arm in ARMS)))
        return
    generate(int(sys.argv[1]), int(sys.argv[2]), sys.argv[3])


def generate(groups, partitions, out):
    stream = "ckpt-g%d-p%d" % (groups, partitions)
    values = {"G": groups, "P": partitions, "PKG": PKG, "STREAM": stream, "ARTIFACT": "test-stream-ckpt-g%d-p%d" % (groups, partitions)}
    src = os.path.join(out, "src/main/java", PKG.replace(".", "/"))
    res = os.path.join(out, "src/main/resources")
    subscribers = "\n".join("    @LoadSubscriber\n    Promise<Unit> onEvent%d(String event);\n" % i for i in range(groups))
    impls = "\n".join("        @Override\n        public Promise<Unit> onEvent%d(String event) {\n            return Promise.success(delivered.incrementAndGet()).mapToUnit();\n        }\n" % i for i in range(groups))
    write(os.path.join(out, "pom.xml"), render(POM, values))
    write(os.path.join(src, "LoadSubscriber.java"), render(QUALIFIER, dict(values, SPI="StreamSubscriber", TARGET="METHOD", NAME="LoadSubscriber")))
    write(os.path.join(src, "LoadPublisher.java"), render(QUALIFIER, dict(values, SPI="StreamPublisher", TARGET="PARAMETER", NAME="LoadPublisher")))
    write(os.path.join(src, "LoadSlice.java"), render(SLICE, dict(values, SUBSCRIBERS=subscribers, IMPLS=impls)))
    write(os.path.join(res, PKG.replace(".", "/"), "routes.toml"), ROUTES)
    write(os.path.join(res, "resources.toml"), render(RESOURCES, values))
    print("generated %s (G=%d P=%d) in %s" % (values["ARTIFACT"], groups, partitions, out))


main()
