SLICE = HEADER + """package @PKG@;

import java.util.concurrent.atomic.AtomicLong;
import java.util.stream.IntStream;

import org.pragmatica.aether.slice.StreamPublisher;
import org.pragmatica.aether.slice.annotation.Slice;
import org.pragmatica.lang.Promise;
import org.pragmatica.lang.Result;
import org.pragmatica.lang.Unit;

import static org.pragmatica.lang.Result.success;


/// S7 load fixture (#2512, #2590), generated by gen.py: @G@ declarative consumer groups (one subscriber method each) over the @P@-partition
/// stream `@STREAM@`, plus a route that publishes a counted batch (the publisher is round-robin over partitions, so `count` events are
/// spread evenly) and a route that reports how many events the runtime delivered to the subscribers on THIS node.
@Slice
public interface LoadSlice {
    record ProduceRequest(int count) {
        public static Result<ProduceRequest> produceRequest(int count) {
            return success(new ProduceRequest(Math.max(0, count)));
        }
    }

    record ProduceResponse(int requested, int published) {
        public static ProduceResponse produceResponse(int requested, int published) {
            return new ProduceResponse(requested, published);
        }
    }

    record ReceivedRequest() {}

    record ReceivedResponse(long delivered) {
        public static ReceivedResponse receivedResponse(long delivered) {
            return new ReceivedResponse(delivered);
        }
    }

    Promise<ProduceResponse> produce(ProduceRequest request);
    Promise<ReceivedResponse> received(ReceivedRequest request);

@SUBSCRIBERS@

    static LoadSlice loadSlice(@LoadPublisher StreamPublisher<String> publisher) {
        return new loadSlice(publisher, new AtomicLong());
    }

    record loadSlice(StreamPublisher<String> publisher, AtomicLong delivered) implements LoadSlice {
        @Override
        public Promise<ProduceResponse> produce(ProduceRequest request) {
            return publisher.publishBatch(IntStream.range(0, request.count()).mapToObj(i -> "e" + i).toList())
                            .map(outcomes -> ProduceResponse.produceResponse(request.count(), outcomes.size()));
        }

        @Override
        public Promise<ReceivedResponse> received(ReceivedRequest request) {
            return Promise.success(ReceivedResponse.receivedResponse(delivered.get()));
        }

@IMPLS@
    }
}
"""

