#!/bin/bash
# node.sh — host-side process control for one Aether node of the arm X/K harness. Runs ON the host.
#
#   node.sh start <root> <id> <role> <cluster-port> <mgmt-port> <app-port> <agent-port|0> <peers> <advertise-host> <heap>
#   node.sh kill  <root> <id>      SIGKILL: the crash used by S3/S4 (a process dies; the VM stays)
#   node.sh stop  <root> <id>      SIGTERM, then SIGKILL after 30 s
#   node.sh pid   <root> <id>      prints the pid when the process is alive, exits 1 otherwise
#   node.sh sample <root>          one line: epoch, loadavg(1,5,15), cpu busy % over 1 s, per-node RSS of the live nodes
#
# Credentials come from <root>/secrets/{cluster-secret,api-keys} (0600), written by the orchestrator, never from argv.
# No node is given a cloud provider section or a provider token, so no node can create a server (auto-heal and the
# topology manager have no compute provider to call).
set -euo pipefail
OP=$1; ROOT=$2

start() {
    local id=$1 role=$2 cport=$3 mport=$4 aport=$5 agentport=$6 peers=$7 adv=$8 heap=$9
    local dir="$ROOT/nodes/$id"
    if [ -f "$dir/pid" ] && kill -0 "$(cat "$dir/pid")" 2>/dev/null; then echo "node $id already running" >&2; exit 3; fi
    mkdir -p "$dir/state" "$dir/data"
    cat > "$dir/aether.toml" <<EOF
# arm X/K harness node $id ($role) — generated by node.sh
[cluster]
tls = false

[slice]
repositories = ["builtin"]

[app-http]
enabled = true
port = $aport
EOF
    local agent=""
    if [ "$agentport" != 0 ]; then agent="-javaagent:$ROOT/bin/m1probe.jar=port=$agentport"; fi
    (
        cd "$dir"
        export AETHER_CLUSTER_NAME=armxk
        export AETHER_ROLE="$role"
        export CORE_MAX=5
        export AETHER_ADVERTISE_HOST="$adv"
        AETHER_CLUSTER_SECRET="$(cat "$ROOT/secrets/cluster-secret")"; export AETHER_CLUSTER_SECRET
        AETHER_API_KEYS="$(cat "$ROOT/secrets/api-keys")"; export AETHER_API_KEYS
        nohup setsid java -XX:+ExitOnOutOfMemoryError "-Xmx$heap" -XX:+UseZGC -Djava.net.preferIPv4Stack=true \
            --add-opens java.base/java.lang=ALL-UNNAMED $agent \
            "-Daether.state.dir=$dir/state" "-Daether.storage.defaultRoot=$dir/data" \
            -jar "$ROOT/bin/aether-node.jar" "--config=$dir/aether.toml" "--node-id=$id" \
            "--port=$cport" "--management-port=$mport" "--peers=$peers" \
            > "$dir/node.log" 2>&1 < /dev/null &
        echo $! > "$dir/pid"
    )
    echo "started $id pid $(cat "$dir/pid")"
}

pid_of() {
    local f="$ROOT/nodes/$1/pid"
    [ -f "$f" ] && kill -0 "$(cat "$f")" 2>/dev/null && cat "$f"
}

case "$OP" in
    start) shift 2; start "$@" ;;
    kill) p=$(pid_of "$3") && kill -9 "$p" && echo "killed $3 pid $p" ;;
    stop)
        p=$(pid_of "$3") || exit 0
        kill -TERM "$p"
        for _ in $(seq 30); do kill -0 "$p" 2>/dev/null || exit 0; sleep 1; done
        kill -9 "$p" 2>/dev/null || true ;;
    pid) pid_of "$3" ;;
    sample)
        read -r _ a b c d e f g h _ < /proc/stat; t1=$((a+b+c+d+e+f+g+h)); i1=$((d+e))
        sleep 1
        read -r _ a b c d e f g h _ < /proc/stat; t2=$((a+b+c+d+e+f+g+h)); i2=$((d+e))
        busy=$(( (100 * ((t2-t1) - (i2-i1))) / ((t2-t1) > 0 ? (t2-t1) : 1) ))
        rss=""
        for d in "$ROOT"/nodes/*/; do
            id=$(basename "$d"); p=$(pid_of "$id") || continue
            rss="$rss $id=$(awk '/VmRSS/{print $2}' "/proc/$p/status")kB"
        done
        echo "$(date +%s) load=$(cut -d' ' -f1-3 /proc/loadavg | tr ' ' ',') cpu=${busy}% nproc=$(nproc)$rss" ;;
    *) echo "unknown op $OP" >&2; exit 2 ;;
esac
