package org.pragmatica.serialization.json.spi;

import java.lang.annotation.ElementType;
import java.lang.annotation.Retention;
import java.lang.annotation.RetentionPolicy;
import java.lang.annotation.Target;


/// Marks a class generated by the JSON codec generators and names what it was generated for: the `@Json` type of an
/// entry point, the type set of a registry, the slice of a route holder. The generators read it from a class already
/// on the class path or in the output directory before writing one of the same name: the same source may regenerate
/// its own class (an incremental build), any other source is refused with a compile error, so one generated class
/// never silently replaces another's. Class retention: the compiler reads it from class files, the runtime never does.
@Target(ElementType.TYPE)
@Retention(RetentionPolicy.CLASS)
public @interface GeneratedFor {
    /// The source the class was generated for.
    String value();
}
