package org.pragmatica.serialization.json;

import org.junit.jupiter.api.Test;

import static org.junit.jupiter.api.Assertions.assertEquals;

/// The table in EiselLemireTable is generated by src/build/gen_eisel_lemire_table.py (Python); this is the
/// independent second implementation it must agree with, word for word.
class EiselLemireTableTest {
    // The generated literal table must equal an independent BigInteger computation, word for word.
    @Test
    void eiselLemireTable_equalsBigIntegerComputation() {
        var two128 = java.math.BigInteger.ONE.shiftLeft(128);
        var two127 = java.math.BigInteger.ONE.shiftLeft(127);
        var five = java.math.BigInteger.valueOf(5);
        for (int q = EiselLemireTable.SMALLEST_POWER; q <= EiselLemireTable.LARGEST_POWER; q++) {
            java.math.BigInteger c;
            if (q < 0) {
                var power5 = five.pow(-q);
                var z = power5.subtract(java.math.BigInteger.ONE).bitLength();
                c = java.math.BigInteger.ONE.shiftLeft(q >= -27 ? z + 127 : 2 * z + 128).divide(power5).add(java.math.BigInteger.ONE);
                while (c.compareTo(two128) >= 0) {
                    c = c.shiftRight(1);
                }
            } else {
                c = five.pow(q);
                while (c.compareTo(two127) < 0) {
                    c = c.shiftLeft(1);
                }
                while (c.compareTo(two128) >= 0) {
                    c = c.shiftRight(1);
                }
            }
            var index = q - EiselLemireTable.SMALLEST_POWER;
            assertEquals(c.shiftRight(64).longValue(), EiselLemireTable.HIGH[index], "HIGH q=" + q);
            assertEquals(c.longValue(), EiselLemireTable.LOW[index], "LOW q=" + q);
        }
        assertEquals(EiselLemireTable.LARGEST_POWER - EiselLemireTable.SMALLEST_POWER + 1, EiselLemireTable.HIGH.length);
    }
}
