"""Emits EiselLemireTable.java: 128-bit normalized mantissas of 10^q, q in [-342, 308], split into
high/low 64-bit words. Rules as in the published fast_float/simdjson tables: truncated for q >= 0, a
one-ulp-high reciprocal for q < 0. Independent of the Java oracle in EiselLemireTableTest, on purpose.

Usage: src/build/gen_eisel_lemire_table.py > src/main/java/org/pragmatica/serialization/json/EiselLemireTable.java"""

