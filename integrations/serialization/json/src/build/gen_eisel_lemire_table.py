def mantissa(q):
    if q < 0:
        power5 = 5 ** -q
        z = (power5 - 1).bit_length()
        b = z + 127 if q >= -27 else 2 * z + 128
        c = (1 << b) // power5 + 1
        while c >= 1 << 128:
            c >>= 1
        return c
    c = 5 ** q
    while c < 1 << 127:
        c <<= 1
    while c >= 1 << 128:
        c >>= 1
    return c


def literal(word):
    return f"0x{word:016X}L"


def array(name, words):
    lines = [f"    static final long[] {name} = {{"]
    for i in range(0, len(words), 4):
        lines.append("        " + ", ".join(literal(w) for w in words[i:i + 4]) + ",")
    lines.append("    };")
    return lines


values = [mantissa(q) for q in range(SMALLEST, LARGEST + 1)]
high = [v >> 64 for v in values]
low = [v & ((1 << 64) - 1) for v in values]
out = [LICENSE + "package org.pragmatica.serialization.json;", "",
       "/// GENERATED by src/build/gen_eisel_lemire_table.py: do not edit. 128-bit normalized mantissas of",
       f"/// 10^q for q in [{SMALLEST}, {LARGEST}] (index q - ({SMALLEST})), as high and low words. Checked against an",
       "/// independent BigInteger computation by EiselLemireTableTest.",
       "final class EiselLemireTable {",
       f"    static final int SMALLEST_POWER = {SMALLEST};",
       f"    static final int LARGEST_POWER = {LARGEST};",
       ""]
out += array("HIGH", high) + [""] + array("LOW", low)
out += ["", "    private EiselLemireTable() {}", "}"]
print("\n".join(out))
