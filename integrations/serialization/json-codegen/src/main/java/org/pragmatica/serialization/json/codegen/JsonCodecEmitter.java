package org.pragmatica.serialization.json.codegen;

import javax.lang.model.element.Element;
import javax.lang.model.element.TypeElement;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.HashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;

/// Emits the source of one codec holder: a public interface with a nested `XxxJson` interface (static `write`
/// and `read`) per record or enum, and a `CODECS` map from each record and enum class to its codec. Every
/// type a codec touches is called through a static method, so call sites stay monomorphic and inline.
final class JsonCodecEmitter {
    private static final String RT = "org.pragmatica.serialization.json.";

    private final JsonTypeAnalyzer analyzer;
    private final Map<String, String> names = new HashMap<>();
    private final Set<String> taken = new HashSet<>();

    JsonCodecEmitter(JsonTypeAnalyzer analyzer) {
        this.analyzer = analyzer;
    }

    String emit(String packageName, String holderName, String generatedBy) {
        analyzer.records().keySet().forEach(name -> assignName(analyzer.records().get(name).element()));
        analyzer.enums().keySet().forEach(name -> assignName(analyzer.enums().get(name).element()));
        var out = new ArrayList<String>();

        out.add("package " + packageName + ";");
        out.add("");
        out.add("/// GENERATED by " + generatedBy + ": reflection-free JSON codecs. Do not edit.");
        out.add("public interface " + holderName + " {");
        var blocks = new ArrayList<List<String>>();

        analyzer.enums().values().forEach(definition -> blocks.add(emitEnum(definition)));
        analyzer.records().values().forEach(definition -> blocks.add(emitRecord(definition)));
        for (var block : blocks) {
            out.addAll(block);
            out.add("");
        }
        out.addAll(emitRegistry());
        out.add("}");
        return String.join("\n", out) + "\n";
    }

    // ---- naming --------------------------------------------------------------------------------

    private void assignName(TypeElement element) {
        var key = element.getQualifiedName().toString();

        if (names.containsKey(key)) {
            return;
        }
        var parts = new ArrayList<String>();

        for (Element current = element; current instanceof TypeElement type; current = current.getEnclosingElement()) {
            parts.addFirst(type.getSimpleName().toString());
        }
        var base = String.join("_", parts) + "Json";
        var name = base;

        for (int i = 2; !taken.add(name); i++) {
            name = base + i;
        }
        names.put(key, name);
    }

    private String codecName(TypeElement element) {
        return names.get(element.getQualifiedName().toString());
    }

    private static String typeName(TypeElement element) {
        return element.getQualifiedName().toString();
    }

    // ---- enums ---------------------------------------------------------------------------------

    private List<String> emitEnum(JsonType.EnumDefinition definition) {
        var type = typeName(definition.element());
        var name = codecName(definition.element());
        var constants = String.join(", ", definition.constants().stream().map(c -> "\"" + c + "\"").toList());
        var read = definition.unknownIndex() >= 0
                   ? "in.readEnumOr(CONSTANTS, " + definition.unknownIndex() + ")"
                   : "in.readEnum(CONSTANTS)";

        return List.of("    interface " + name + " {",
                       "        " + RT + "FieldNames CONSTANTS = " + RT + "FieldNames.fieldNames(" + constants + ");",
                       "        " + type + "[] VALUES = " + type + ".values();",
                       "        " + RT + "JsonTypeCodec<" + type + "> CODEC = " + RT + "JsonTypeCodec.jsonTypeCodec(" + name + "::write, " + name + "::read);",
                       "",
                       "        static void write(" + RT + "JsonWriter out, " + type + " value) {",
                       "            out.writeRaw(CONSTANTS.quoted(value.ordinal()));",
                       "        }",
                       "",
                       "        static " + type + " read(" + RT + "JsonReader in) {",
                       "            var index = " + read + ";",
                       "            return index < 0",
                       "                   ? null",
                       "                   : VALUES[index];",
                       "        }",
                       "    }");
    }

    // ---- records -------------------------------------------------------------------------------

    private List<String> emitRecord(JsonType.RecordDefinition definition) {
        return definition.isValueObject()
               ? emitValueObject(definition)
               : emitObject(definition);
    }

    private List<String> emitValueObject(JsonType.RecordDefinition definition) {
        var type = typeName(definition.element());
        var name = codecName(definition.element());
        var component = definition.components().getFirst();
        var lines = new ArrayList<String>();

        lines.add("    interface " + name + " {");
        lines.add("        " + RT + "JsonTypeCodec<" + type + "> CODEC = " + RT + "JsonTypeCodec.jsonTypeCodec(" + name + "::write, " + name + "::read);");
        lines.add("");
        lines.add("        static void write(" + RT + "JsonWriter out, " + type + " value) {");
        lines.addAll(writeValue(component.type(), "value." + component.name() + "()", "            "));
        lines.add("        }");
        lines.add("");
        lines.add("        /// The value object as its factory judges the bare value.");
        lines.add("        static org.pragmatica.lang.Result<" + type + "> parse(" + RT + "JsonReader in) {");
        lines.add("            return " + type + "." + definition.factory().getSimpleName() + "(" + readScalar((JsonType.Scalar) component.type()) + ");");
        lines.add("        }");
        lines.add("");
        lines.add("        static " + type + " read(" + RT + "JsonReader in) {");
        lines.add("            return in.accept(parse(in), \"" + definition.element().getSimpleName() + "\");");
        lines.add("        }");
        lines.add("    }");
        return lines;
    }

    private List<String> emitObject(JsonType.RecordDefinition definition) {
        var type = typeName(definition.element());
        var name = codecName(definition.element());
        var components = definition.components();
        var lines = new ArrayList<String>();
        var nameList = String.join(", ", components.stream().map(c -> "\"" + c.name() + "\"").toList());
        var required = 0L;

        for (int i = 0; i < components.size(); i++) {
            if (!(components.get(i).type() instanceof JsonType.OptionalOf)) {
                required |= 1L << i;
            }
        }
        lines.add("    interface " + name + " {");
        lines.add("        " + RT + "FieldNames NAMES = " + RT + "FieldNames.fieldNames(" + nameList + ");");
        lines.add("        long REQUIRED = " + required + "L;");
        lines.add("        " + RT + "JsonTypeCodec<" + type + "> CODEC = " + RT + "JsonTypeCodec.jsonTypeCodec(" + name + "::write, " + name + "::read);");
        lines.add("");
        lines.add("        static void write(" + RT + "JsonWriter out, " + type + " value) {");
        lines.add("            out.writeByte('{');");
        for (int i = 0; i < components.size(); i++) {
            var component = components.get(i);

            lines.add("            out.writeRaw(NAMES." + (i == 0 ? "first" : "next") + "(" + i + "));");
            lines.addAll(writeField(component, "value." + component.name() + "()", "            "));
        }
        if (components.isEmpty()) {
            lines.add("            // no components");
        }
        lines.add("            out.writeByte('}');");
        lines.add("        }");
        lines.add("");
        lines.add("        static " + type + " read(" + RT + "JsonReader in) {");
        lines.add("            if (!in.beginObject()) {");
        lines.add("                return null;");
        lines.add("            }");
        for (var component : components) {
            lines.add("            " + localType(component.type()) + " f_" + component.name() + " = " + defaultValue(component.type()) + ";");
        }
        lines.add("            var seen = 0L;");
        lines.add("            var expected = 0;");
        lines.add("            for (var field = in.firstField(NAMES); field != " + RT + "JsonReader.END_OF_OBJECT; field = in.nextField(NAMES, expected)) {");
        lines.add("                switch (field) {");
        for (int i = 0; i < components.size(); i++) {
            var component = components.get(i);

            lines.add("                    case " + i + " -> f_" + component.name() + " = " + readField(component, i) + ";");
        }
        lines.add("                    default -> in.skipValue();");
        lines.add("                }");
        lines.add("                if (field >= 0) {");
        lines.add("                    seen |= 1L << field;");
        lines.add("                    expected = field + 1;");
        lines.add("                }");
        lines.add("            }");
        for (int i = 0; i < components.size(); i++) {
            if (components.get(i).type() instanceof JsonType.OptionalOf) {
                lines.add("            if ((seen & " + (1L << i) + "L) == 0) {");
                lines.add("                f_" + components.get(i).name() + " = org.pragmatica.lang.Option.none();");
                lines.add("            }");
            }
        }
        lines.add("            if ((seen & REQUIRED) != REQUIRED) {");
        lines.add("                in.failMissing(NAMES, seen, REQUIRED);");
        lines.add("            }");
        lines.add("            if (in.hasError()) {");
        lines.add("                return null;");
        lines.add("            }");
        var args = String.join(", ", components.stream().map(c -> "f_" + c.name()).toList());

        lines.add(definition.factory() == null
                  ? "            return new " + type + "(" + args + ");"
                  : "            return in.accept(" + type + "." + definition.factory().getSimpleName() + "(" + args + "), \""
                    + definition.element().getSimpleName() + "\");");
        lines.add("        }");
        for (int i = 0; i < components.size(); i++) {
            var component = components.get(i);

            if (needsHelper(component.type())) {
                lines.add("");
                lines.addAll(readHelper(component, i));
            }
        }
        // Helpers for nested containers, collected while the component helpers above were emitted.
        for (int i = 0; i < extraHelpers.size(); i++) {
            lines.add("");
            lines.addAll(extraHelpers.get(i));
        }
        extraHelpers.clear();
        lines.add("    }");
        return lines;
    }

    // ---- writing -------------------------------------------------------------------------------

    private List<String> writeField(JsonType.Component component, String expr, String ind) {
        return writeValue(component.type(), expr, ind);
    }

    private List<String> writeValue(JsonType type, String expr, String ind) {
        return switch (type) {
            case JsonType.Scalar scalar -> List.of(ind + writeScalar(scalar, expr) + ";");
            case JsonType.EnumRef ref -> List.of(ind + codecName(ref.element()) + ".write(out, " + expr + ");");
            case JsonType.RecordRef ref -> List.of(ind + codecName(ref.element()) + ".write(out, " + expr + ");");
            case JsonType.OptionalOf optional -> writeOptional(optional, expr, ind);
            case JsonType.ListOf list -> writeList(list, expr, ind);
            case JsonType.MapOf map -> writeMap(map, expr, ind);
        };
    }

    private static String writeScalar(JsonType.Scalar scalar, String expr) {
        return switch (scalar.kind()) {
            case INT -> "out.writeInt(" + expr + ")";
            case LONG -> "out.writeLong(" + expr + ")";
            case DOUBLE -> "out.writeDouble(" + expr + ")";
            case BOOLEAN -> "out.writeBoolean(" + expr + ")";
            case STRING -> "out.writeString(" + expr + ")";
            case DECIMAL -> "out.writeDecimal(" + expr + ")";
            case INSTANT -> "out.writeInstant(" + expr + ")";
            case UUID -> "out.writeUuid(" + expr + ")";
            case LOCAL_DATE -> "out.writeLocalDate(" + expr + ")";
            case CURRENCY -> "out.writeAsciiString(" + expr + ".getCurrencyCode())";
        };
    }

    private int depth;

    private String local(String base) {
        return base + (depth == 0 ? "" : String.valueOf(depth));
    }

    private List<String> writeOptional(JsonType.OptionalOf optional, String expr, String ind) {
        var boxed = javaType(optional.element());
        var present = local("present");
        var lines = new ArrayList<String>();

        lines.add(ind + "switch (" + expr + ") {");
        lines.add(ind + "    case org.pragmatica.lang.Option.Some<" + boxed + ">(var " + present + ") -> {");
        depth++;
        lines.addAll(writeValue(optional.element(), present, ind + "        "));
        depth--;
        lines.add(ind + "    }");
        lines.add(ind + "    case org.pragmatica.lang.Option.None<" + boxed + "> _ -> out.writeNull();");
        lines.add(ind + "}");
        return lines;
    }

    private List<String> writeList(JsonType.ListOf list, String expr, String ind) {
        var lines = new ArrayList<String>();
        var element = local("element");
        var first = local("first");

        lines.add(ind + "out.writeByte('[');");
        lines.add(ind + "var " + first + " = true;");
        lines.add(ind + "for (var " + element + " : " + expr + ") {");
        lines.add(ind + "    if (!" + first + ") {");
        lines.add(ind + "        out.writeByte(',');");
        lines.add(ind + "    }");
        lines.add(ind + "    " + first + " = false;");
        depth++;
        lines.addAll(writeValue(list.element(), element, ind + "    "));
        depth--;
        lines.add(ind + "}");
        lines.add(ind + "out.writeByte(']');");
        return wrapBlock(lines, ind);
    }

    private List<String> writeMap(JsonType.MapOf map, String expr, String ind) {
        var lines = new ArrayList<String>();
        var entry = local("entry");
        var first = local("first");

        lines.add(ind + "out.writeByte('{');");
        lines.add(ind + "var " + first + " = true;");
        lines.add(ind + "for (var " + entry + " : " + expr + ".entrySet()) {");
        lines.add(ind + "    if (!" + first + ") {");
        lines.add(ind + "        out.writeByte(',');");
        lines.add(ind + "    }");
        lines.add(ind + "    " + first + " = false;");
        lines.add(ind + "    " + writeKey(map.key(), entry + ".getKey()") + ";");
        lines.add(ind + "    out.writeByte(':');");
        depth++;
        lines.addAll(writeValue(map.value(), entry + ".getValue()", ind + "    "));
        depth--;
        lines.add(ind + "}");
        lines.add(ind + "out.writeByte('}');");
        return wrapBlock(lines, ind);
    }

    // A block keeps loop locals from colliding with a sibling field's loop in the same method.
    private static List<String> wrapBlock(List<String> lines, String ind) {
        var wrapped = new ArrayList<String>();

        wrapped.add(ind + "{");
        lines.forEach(line -> wrapped.add("    " + line));
        wrapped.add(ind + "}");
        return wrapped;
    }

    private String writeKey(JsonType key, String expr) {
        return switch (key) {
            case JsonType.EnumRef ref -> "out.writeRaw(" + codecName(ref.element()) + ".CONSTANTS.quoted(" + expr + ".ordinal()))";
            case JsonType.RecordRef ref -> "out.writeString(" + expr + "."
                                           + analyzer.records().get(typeName(ref.element())).components().getFirst().name() + "())";
            default -> "out.writeString(" + expr + ")";
        };
    }

    // ---- reading -------------------------------------------------------------------------------

    private String readField(JsonType.Component component, int index) {
        var type = component.type();

        if (needsHelper(type)) {
            return "read_" + component.name() + "(in)";
        }
        if (type instanceof JsonType.RecordRef ref && isValueObject(ref)) {
            return "in.accept(" + codecName(ref.element()) + ".parse(in), NAMES, " + index + ")";
        }
        return readValue(type);
    }

    private String readValue(JsonType type) {
        return switch (type) {
            case JsonType.Scalar scalar -> readScalar(scalar);
            case JsonType.EnumRef ref -> codecName(ref.element()) + ".read(in)";
            case JsonType.RecordRef ref -> codecName(ref.element()) + ".read(in)";
            default -> throw new IllegalStateException("container read is emitted as a helper: " + type);
        };
    }

    private static String readScalar(JsonType.Scalar scalar) {
        return switch (scalar.kind()) {
            case INT -> "in.readInt()";
            case LONG -> "in.readLong()";
            case DOUBLE -> "in.readDouble()";
            case BOOLEAN -> "in.readBoolean()";
            case STRING -> "in.readString()";
            case DECIMAL -> "in.readDecimal()";
            case INSTANT -> "in.readInstant()";
            case UUID -> "in.readUuid()";
            case LOCAL_DATE -> "in.readLocalDate()";
            case CURRENCY -> "in.readCurrency()";
        };
    }

    private static boolean needsHelper(JsonType type) {
        return type instanceof JsonType.OptionalOf || type instanceof JsonType.ListOf || type instanceof JsonType.MapOf;
    }

    private boolean isValueObject(JsonType.RecordRef ref) {
        return analyzer.records().get(typeName(ref.element())).isValueObject();
    }

    private List<String> readHelper(JsonType.Component component, int index) {
        var lines = new ArrayList<String>();

        lines.add("        private static " + javaType(component.type()) + " read_" + component.name() + "(" + RT + "JsonReader in) {");
        lines.addAll(readContainerBody(component.type(), "            "));
        lines.add("        }");
        return lines;
    }

    // Statements that read one value of a container type and `return` it.
    private List<String> readContainerBody(JsonType type, String ind) {
        return switch (type) {
            case JsonType.OptionalOf optional -> List.of(ind + "return in.isNull()",
                                                         ind + "       ? org.pragmatica.lang.Option.none()",
                                                         ind + "       : org.pragmatica.lang.Option.some(" + readElement(optional.element()) + ");");
            case JsonType.ListOf list -> {
                var impl = list.set() ? "java.util.LinkedHashSet" : "java.util.ArrayList";
                yield List.of(ind + "var values = new " + impl + "<" + javaType(list.element()) + ">();",
                              ind + "if (in.beginArray()) {",
                              ind + "    for (var more = in.firstElement(); more; more = in.nextElement()) {",
                              ind + "        values.add(" + readElement(list.element()) + ");",
                              ind + "    }",
                              ind + "}",
                              ind + "return values;");
            }
            case JsonType.MapOf map -> List.of(ind + "var values = new java.util.LinkedHashMap<" + javaType(map.key()) + ", " + javaType(map.value()) + ">();",
                                               ind + "if (in.beginObject()) {",
                                               ind + "    for (var more = in.firstEntry(); more; more = in.nextEntry()) {",
                                               ind + "        values.put(" + readKey(map.key()) + ", " + readElement(map.value()) + ");",
                                               ind + "    }",
                                               ind + "}",
                                               ind + "return values;");
            default -> List.of(ind + "return " + readValue(type) + ";");
        };
    }

    // An element of a container: nested containers go through a lambda-free inline helper chain.
    private String readElement(JsonType type) {
        if (type instanceof JsonType.RecordRef ref && isValueObject(ref)) {
            return codecName(ref.element()) + ".read(in)";
        }
        if (needsHelper(type)) {
            return nestedHelper(type);
        }
        return readValue(type);
    }

    private final List<List<String>> extraHelpers = new ArrayList<>();
    private int helperCount;

    // Nested containers (List<List<X>>, Map<String, Option<Y>>) get their own private static method.
    private String nestedHelper(JsonType type) {
        var name = "read_nested" + helperCount++;
        var lines = new ArrayList<String>();

        lines.add("        private static " + javaType(type) + " " + name + "(" + RT + "JsonReader in) {");
        lines.addAll(readContainerBody(type, "            "));
        lines.add("        }");
        extraHelpers.add(lines);
        return name + "(in)";
    }

    private String readKey(JsonType key) {
        return switch (key) {
            case JsonType.EnumRef ref -> codecName(ref.element()) + ".VALUES[Math.max(0, in.readEnumKey(" + codecName(ref.element()) + ".CONSTANTS))]";
            case JsonType.RecordRef ref -> "in.accept(" + typeName(ref.element()) + "."
                                           + analyzer.records().get(typeName(ref.element())).factory().getSimpleName()
                                           + "(in.readKey()), \"" + ref.element().getSimpleName() + "\")";
            default -> "in.readKey()";
        };
    }

    // ---- types ---------------------------------------------------------------------------------

    private String javaType(JsonType type) {
        return switch (type) {
            case JsonType.Scalar scalar -> switch (scalar.kind()) {
                case INT -> "java.lang.Integer";
                case LONG -> "java.lang.Long";
                case DOUBLE -> "java.lang.Double";
                case BOOLEAN -> "java.lang.Boolean";
                case STRING -> "java.lang.String";
                case DECIMAL -> "java.math.BigDecimal";
                case INSTANT -> "java.time.Instant";
                case UUID -> "java.util.UUID";
                case LOCAL_DATE -> "java.time.LocalDate";
                case CURRENCY -> "java.util.Currency";
            };
            case JsonType.EnumRef ref -> typeName(ref.element());
            case JsonType.RecordRef ref -> typeName(ref.element());
            case JsonType.OptionalOf optional -> "org.pragmatica.lang.Option<" + javaType(optional.element()) + ">";
            case JsonType.ListOf list -> (list.set() ? "java.util.Set<" : "java.util.List<") + javaType(list.element()) + ">";
            case JsonType.MapOf map -> "java.util.Map<" + javaType(map.key()) + ", " + javaType(map.value()) + ">";
        };
    }

    // Scalars that read as primitives stay primitive in locals: boxing a long id per field would allocate.
    private String localType(JsonType type) {
        if (type instanceof JsonType.Scalar scalar) {
            return switch (scalar.kind()) {
                case INT -> "int";
                case LONG -> "long";
                case DOUBLE -> "double";
                case BOOLEAN -> "boolean";
                default -> javaType(type);
            };
        }
        return javaType(type);
    }

    private static String defaultValue(JsonType type) {
        if (type instanceof JsonType.Scalar scalar) {
            return switch (scalar.kind()) {
                case INT, LONG, DOUBLE -> "0";
                case BOOLEAN -> "false";
                default -> "null";
            };
        }
        return "null";
    }

    // ---- registry ------------------------------------------------------------------------------

    private List<String> emitRegistry() {
        var entries = new ArrayList<String>();

        analyzer.enums().values().forEach(d -> entries.add("java.util.Map.entry(" + typeName(d.element()) + ".class, " + codecName(d.element()) + ".CODEC)"));
        analyzer.records().values().forEach(d -> entries.add("java.util.Map.entry(" + typeName(d.element()) + ".class, " + codecName(d.element()) + ".CODEC)"));
        var lines = new ArrayList<String>();

        lines.add("    /// Every record and enum codec in this holder, by exact class (records and enums are final).");
        lines.add("    java.util.Map<java.lang.Class<?>, " + RT + "JsonTypeCodec<?>> CODECS = java.util.Map.ofEntries(");
        for (int i = 0; i < entries.size(); i++) {
            lines.add("        " + entries.get(i) + (i + 1 < entries.size() ? "," : ""));
        }
        lines.add("    );");
        return lines;
    }
}
