package org.pragmatica.storage;

import java.nio.file.Path;
import java.util.concurrent.TimeUnit;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.Timeout;
import org.junit.jupiter.api.io.TempDir;

import static org.assertj.core.api.Assertions.assertThat;


/// A write and a ranged read of an object bigger than the heap of the JVM that runs them.
///
/// The probe runs in a child JVM with `-Xmx256m`; the object is 384 MiB, so anything that gathers the object, or all of its
/// blocks, into memory (a `byte[]` reassembly, a list of every chunk) cannot finish. The SHA-256 of the bytes as the
/// producer generated them is compared with the SHA-256 of the bytes read back and with the one the store computed at
/// commit; ranges that cross a block edge, end the object, and start it are compared with regenerated bytes. The data is
/// non-repeating, and the number of block files on disk is asserted, because content addressing would store a repeated
/// block once and a test that cannot tell would pass on a store that wrote almost nothing.
///
/// Mutation: make `open` reassemble the object into one `byte[]`. The child dies with an `OutOfMemoryError` and this test
/// fails on the exit code.
@Timeout(value = 3, unit = TimeUnit.MINUTES, threadMode = Timeout.ThreadMode.SEPARATE_THREAD)
class ContentStoreV2LargeObjectTest {
    private static final long SIZE = 384L * 1024 * 1024;
    private static final long BLOCK = 4L * 1024 * 1024;

    @Test
    void anObjectLargerThanTheHeap_writesAndReadsBackInAChildJvmWith256MiB(@TempDir Path dir) throws Exception {
        var outcome = LargeObjectRun.run(SIZE, dir, 10);
        var diagnostics = "child output:\n" + outcome.output();

        assertThat(outcome.exitCode()).as(diagnostics).isZero();
        assertThat(Long.parseLong(outcome.get("MAX_HEAP_MB"))).as("the child really ran with a small heap: " + diagnostics)
                                                              .isLessThanOrEqualTo(LargeObjectRun.HEAP_MB);
        assertThat(SIZE).as("the object must be larger than the heap, or this test proves nothing")
                        .isGreaterThan(LargeObjectRun.HEAP_MB * 1024L * 1024L);
        assertThat(outcome.get("READ_SHA")).as(diagnostics).isEqualTo(outcome.get("WRITE_SHA"));
        assertThat(outcome.get("STORED_SHA")).as(diagnostics).isEqualTo(outcome.get("WRITE_SHA"));
        assertThat(outcome.get("BYTES_READ")).as(diagnostics).isEqualTo(Long.toString(SIZE));
        assertThat(outcome.get("RANGES_OK")).as(diagnostics).isEqualTo("true");
        assertThat(Long.parseLong(outcome.get("BLOCK_FILES"))).as("every distinct block is on disk: " + diagnostics)
                                                              .isGreaterThanOrEqualTo(SIZE / BLOCK);
    }
}
