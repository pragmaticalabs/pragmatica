-- Conduit schema, PostgreSQL 17. Shared by every implementation; applied by the harness, never by an app
-- (docs/fairness.md F-02). Index choices are justified against the access patterns in docs/workload.md;
-- the "serves:" line under each index names the queries that need it. Plans were checked with EXPLAIN ANALYZE
-- on the seed (schema/seed.sql) under PostgreSQL 17.10 with random_page_cost = 1.1 (docs/fairness.md F-03).
--
-- Conventions:
--   * Ordering-relevant text columns use COLLATE "C" (byte order), so ORDER BY gives the same result whatever
--     the database's default locale (docs/behavior.md B-27, B-40).
--   * Timestamps are truncated to milliseconds before storage (B-48); the CHECKs enforce it.
--   * No triggers, no denormalised counters, no materialised views (F-04).

CREATE TABLE users (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      text COLLATE "C" NOT NULL,
    email         text COLLATE "C" NOT NULL,
    password_hash text NOT NULL,
    bio           text,
    image         text,
    CONSTRAINT users_username_key UNIQUE (username),
    -- serves: GET /profiles/{u}, ?author=, ?favorited=, register/update conflict check (B-19)
    CONSTRAINT users_email_key UNIQUE (email),
    -- serves: login lookup, register/update conflict check
    CONSTRAINT users_email_lowercase CHECK (email = lower(email))
    -- B-12: normalisation is the application's job; the database refuses a row that skipped it
);

CREATE TABLE articles (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug        text COLLATE "C" NOT NULL,
    author_id   bigint NOT NULL REFERENCES users (id),
    title       text NOT NULL,
    description text NOT NULL,
    body        text NOT NULL,
    created_at  timestamptz NOT NULL,
    updated_at  timestamptz NOT NULL,
    CONSTRAINT articles_slug_key UNIQUE (slug),
    -- serves: every /articles/{slug} operation (the most frequent lookup in the workload)
    CONSTRAINT articles_created_at_ms CHECK (created_at = date_trunc('milliseconds', created_at)),
    CONSTRAINT articles_updated_at_ms CHECK (updated_at = date_trunc('milliseconds', updated_at))
);

CREATE INDEX articles_created_idx ON articles (created_at DESC, id DESC);
-- serves: GET /articles global page (ORDER BY created_at DESC, id DESC LIMIT n OFFSET m, B-34): an index
-- scan that stops after offset+limit rows instead of sorting the table. Also lets the planner walk recent
-- articles and probe article_tags for popular tags.

CREATE INDEX articles_author_created_idx ON articles (author_id, created_at DESC, id DESC);
-- serves: ?author= lists and counts (one index range per author), the feed count (one range per followed
-- author); its leading column also covers the author_id foreign key. The feed PAGE is cheaper the other way:
-- the planner walks articles_created_idx and probes follows_pkey until it has offset+limit rows.

CREATE TABLE tags (
    id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text COLLATE "C" NOT NULL,
    CONSTRAINT tags_name_key UNIQUE (name)
    -- serves: ?tag= lookup, tag upsert on article create/update, GET /tags ordered by name (index order)
);

CREATE TABLE article_tags (
    article_id bigint NOT NULL REFERENCES articles (id) ON DELETE CASCADE,
    tag_id     bigint NOT NULL REFERENCES tags (id),
    CONSTRAINT article_tags_pkey PRIMARY KEY (article_id, tag_id)
    -- serves: tagList of a page of articles (article_id = ANY(...)), cascade on article delete
);

CREATE INDEX article_tags_tag_idx ON article_tags (tag_id, article_id);
-- serves: ?tag= filter and its count; GET /tags "attached to at least one article" (EXISTS per tag, B-40)

CREATE TABLE favorites (
    article_id bigint NOT NULL REFERENCES articles (id) ON DELETE CASCADE,
    user_id    bigint NOT NULL REFERENCES users (id),
    CONSTRAINT favorites_pkey PRIMARY KEY (article_id, user_id)
    -- serves: favoritesCount per article (index-only range count), "favorited" for the viewer
    -- (point lookup), idempotent favorite (B-43), cascade on article delete
);

CREATE INDEX favorites_user_idx ON favorites (user_id, article_id);
-- serves: ?favorited= filter and its count

CREATE TABLE follows (
    follower_id bigint NOT NULL REFERENCES users (id),
    followee_id bigint NOT NULL REFERENCES users (id),
    CONSTRAINT follows_pkey PRIMARY KEY (follower_id, followee_id),
    -- serves: feed (followees of the caller), "following" flag (point lookup), idempotent follow (B-42)
    CONSTRAINT follows_not_self CHECK (follower_id <> followee_id)
    -- B-44
);
-- No (followee_id) index: no operation asks "who follows X", and users are never deleted, so the foreign
-- key on followee_id is never checked from the referenced side.

CREATE TABLE comments (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    article_id bigint NOT NULL REFERENCES articles (id) ON DELETE CASCADE,
    author_id  bigint NOT NULL REFERENCES users (id),
    body       text NOT NULL,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT comments_created_at_ms CHECK (created_at = date_trunc('milliseconds', created_at)),
    CONSTRAINT comments_updated_at_ms CHECK (updated_at = date_trunc('milliseconds', updated_at))
);

CREATE INDEX comments_article_idx ON comments (article_id, id);
-- serves: GET /articles/{slug}/comments in id order (B-41) without a sort, cascade on article delete
--
-- Not indexed on purpose: articles.title, comments.author_id, users.bio/image. No query filters on them,
-- and users (the only referenced side) are never deleted.
