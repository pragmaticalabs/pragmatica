#!/usr/bin/env python3
"""The Java files that carry a `tla` / `tlacfg` fragment, and the `paths:` list of tla-models.yml that must name them.

A push to the release branch re-runs the models only when it touches tools/tla/** or one of these files. The list is
generated from extract.py's own discovery (extract.scan over every Java file under --base), never written by hand:

  fragment-paths.py --print   one path per line (files under tools/tla/ are left out: the workflow's tools/tla/** covers them)
  fragment-paths.py --sync    rewrite the generated block of the workflow between the BEGIN and END markers
  fragment-paths.py --check   exit 1, naming every file that carries a fragment but is not listed, and every listed file
                              that carries none (a stale entry)

Options: --base DIR (default .), --workflow FILE (default .github/workflows/tla-models.yml).
"""
import argparse
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import extract  # noqa: E402

BEGIN = '# BEGIN fragment-paths (generated by tools/tla/fragment-paths.py --sync; do not edit by hand)'
END = '# END fragment-paths'
SKIP_DIRS = {'.git', 'target', 'node_modules', '.m2-local', '.tla'}
COVERED = 'tools/tla/'


def discover(base):
    """Sorted relative paths of the Java files under base that hold at least one fragment, outside tools/tla/."""
    found = []
    for d, dirs, files in os.walk(base):
        dirs[:] = sorted(x for x in dirs if x not in SKIP_DIRS)
        for name in files:
            if not name.endswith('.java'):
                continue
            path = os.path.join(d, name)
            rel = os.path.relpath(path, base).replace(os.sep, '/')
            if rel.startswith(COVERED):
                continue
            with open(path, encoding='utf-8', errors='replace') as f:
                if '```tla' not in f.read():
                    continue
            if any(True for _ in extract.scan(path, rel)):
                found.append(rel)
    return sorted(found)


def block_bounds(lines):
    b = [i for i, l in enumerate(lines) if l.strip() == BEGIN]
    e = [i for i, l in enumerate(lines) if l.strip() == END]
    if len(b) != 1 or len(e) != 1 or b[0] > e[0]:
        raise SystemExit(f'fragment-paths: ERROR the workflow needs exactly one BEGIN and one END marker line, in order:\n  {BEGIN}\n  {END}')
    return b[0], e[0]


def listed(workflow):
    with open(workflow, encoding='utf-8') as f:
        lines = f.read().split('\n')
    b, e = block_bounds(lines)
    out = []
    for l in lines[b + 1:e]:
        m = re.match(r"^\s*-\s*'([^']+)'\s*$", l)
        if not m:
            raise SystemExit(f'fragment-paths: ERROR {workflow}:{b + 2}: a line inside the generated block is not a quoted list item: {l!r}')
        out.append(m.group(1))
    return out


def sync(workflow, paths):
    with open(workflow, encoding='utf-8') as f:
        lines = f.read().split('\n')
    b, e = block_bounds(lines)
    indent = re.match(r'^\s*', lines[b]).group(0)
    lines[b + 1:e] = [f"{indent}- '{p}'" for p in paths]
    with open(workflow, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines))


def main():
    ap = argparse.ArgumentParser()
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument('--print', action='store_true', dest='show')
    g.add_argument('--sync', action='store_true')
    g.add_argument('--check', action='store_true')
    ap.add_argument('--base', default='.')
    ap.add_argument('--workflow', default='.github/workflows/tla-models.yml')
    a = ap.parse_args()
    try:
        paths = discover(a.base)
    except extract.Fail as e:
        print(f'fragment-paths: ERROR {e}', file=sys.stderr)
        sys.exit(2)
    if a.show:
        print('\n'.join(paths))
    elif a.sync:
        sync(a.workflow, paths)
        print(f'fragment-paths: {len(paths)} paths written to {a.workflow}')
    else:
        have = listed(a.workflow)
        missing = sorted(set(paths) - set(have))
        stale = sorted(set(have) - set(paths))
        dup = sorted({p for p in have if have.count(p) > 1})
        for p in missing:
            print(f'fragment-paths: RED {p} carries a tla fragment but is not in the paths list of {a.workflow}')
        for p in stale:
            print(f'fragment-paths: RED {p} is in the paths list of {a.workflow} but carries no tla fragment (or does not exist)')
        for p in dup:
            print(f'fragment-paths: RED {p} is listed twice in {a.workflow}')
        if missing or stale or dup:
            print('fragment-paths: run tools/tla/fragment-paths.py --sync')
            sys.exit(1)
        print(f'fragment-paths: OK {len(paths)} fragment files, all listed in {a.workflow}')


if __name__ == '__main__':
    main()
