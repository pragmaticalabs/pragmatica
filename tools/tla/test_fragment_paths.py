"""Tests of fragment-paths.py: the paths list of tla-models.yml must name every Java file that carries a tla fragment.

Every case is a named test; the last two run over the real repository and over a copy of the real workflow with one
entry removed (a fragment file missing from the list must turn the check red).
"""
import os
import shutil
import subprocess
import sys
import tempfile
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
SCRIPT = os.path.join(HERE, 'fragment-paths.py')
REPO = os.path.abspath(os.path.join(HERE, '..', '..'))
REAL_WORKFLOW = os.path.join(REPO, '.github', 'workflows', 'tla-models.yml')

FRAGMENT = '/// ```tla M:head\n/// EXTENDS Naturals\n/// ```\nclass A {}\n'
WORKFLOW = """on:
  push:
    paths:
      - 'tools/tla/**'
      # BEGIN fragment-paths (generated by tools/tla/fragment-paths.py --sync; do not edit by hand)
{entries}
      # END fragment-paths
"""


def run(args):
    p = subprocess.run([sys.executable, SCRIPT] + args, capture_output=True, text=True)
    return p.returncode, p.stdout + p.stderr


class FragmentPaths(unittest.TestCase):
    def setUp(self):
        self.d = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, self.d)
        self.wf = os.path.join(self.d, 'wf.yml')
        self.models = os.path.join(self.d, 'models.tsv')
        self.model_rows('M')

    def java(self, rel, text=FRAGMENT):
        p = os.path.join(self.d, rel)
        os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, 'w') as f:
            f.write(text)

    def workflow(self, *entries):
        with open(self.wf, 'w') as f:
            f.write(WORKFLOW.format(entries='\n'.join(f"      - '{e}'" for e in entries)))

    def model_rows(self, *modules, extra=''):
        with open(self.models, 'w') as f:
            f.write(extra + ''.join(f'{m}\tsrc\tok\tpass\t-\t-\twhat\n' for m in modules))

    def check(self):
        return run(['--check', '--base', self.d, '--workflow', self.wf, '--models', self.models])

    def test_all_fragment_files_listed_is_green(self):
        self.java('m/A.java'); self.java('m/B.java')
        self.workflow('m/A.java', 'm/B.java')
        rc, out = self.check()
        self.assertEqual(rc, 0, out)
        self.assertIn('OK 2 fragment files', out)

    def test_fragment_file_missing_from_list_is_red_and_named(self):
        self.java('m/A.java'); self.java('m/B.java')
        self.workflow('m/A.java')
        rc, out = self.check()
        self.assertEqual(rc, 1, out)
        self.assertIn('RED m/B.java carries a tla fragment but is not in the paths list', out)

    def test_stale_entry_is_red_and_named(self):
        self.java('m/A.java')
        self.workflow('m/A.java', 'm/Gone.java')
        rc, out = self.check()
        self.assertEqual(rc, 1, out)
        self.assertIn('RED m/Gone.java is in the paths list', out)

    def test_duplicate_entry_is_red(self):
        self.java('m/A.java')
        self.workflow('m/A.java', 'm/A.java')
        rc, out = self.check()
        self.assertEqual(rc, 1, out)
        self.assertIn('RED m/A.java is listed twice', out)

    def test_java_file_without_fragment_is_not_required(self):
        self.java('m/A.java'); self.java('m/Plain.java', 'class Plain {}\n')
        self.workflow('m/A.java')
        rc, out = self.check()
        self.assertEqual(rc, 0, out)

    def test_fence_text_that_is_not_a_fragment_is_not_required(self):
        self.java('m/A.java'); self.java('m/Doc.java', '/// ```java\n/// int x;\n/// ```\nclass Doc {}\n')
        self.java('m/Mention.java', '// the ```tla convention is described elsewhere\nclass Mention {}\n')
        self.workflow('m/A.java')
        rc, out = self.check()
        self.assertEqual(rc, 0, out)

    def test_file_under_tools_tla_is_covered_by_the_glob_and_not_listed(self):
        self.java('tools/tla/fixtures/F.java'); self.java('m/A.java')
        self.workflow('m/A.java')
        rc, out = self.check()
        self.assertEqual(rc, 0, out)

    def test_target_directory_is_not_scanned(self):
        self.java('m/A.java'); self.java('m/target/generated/G.java')
        self.workflow('m/A.java')
        rc, out = self.check()
        self.assertEqual(rc, 0, out)

    def test_malformed_fragment_is_an_error_not_silence(self):
        self.java('m/Bad.java', '/// ```tla NoPart\n/// x\n/// ```\nclass Bad {}\n')
        self.workflow()
        rc, out = self.check()
        self.assertEqual(rc, 2, out)
        self.assertIn('is not <Module>:<Part>', out)

    def test_markers_missing_is_an_error(self):
        self.java('m/A.java')
        with open(self.wf, 'w') as f:
            f.write('on: push\n')
        rc, out = self.check()
        self.assertNotEqual(rc, 0, out)
        self.assertIn('BEGIN and one END marker', out)

    def test_sync_makes_check_green_and_keeps_text_outside_the_block(self):
        self.java('m/A.java'); self.java('m/B.java')
        self.workflow('m/Stale.java')
        rc, out = run(['--sync', '--base', self.d, '--workflow', self.wf])
        self.assertEqual(rc, 0, out)
        rc, out = self.check()
        self.assertEqual(rc, 0, out)
        with open(self.wf) as f:
            text = f.read()
        self.assertIn("      - 'tools/tla/**'\n", text)
        self.assertNotIn('Stale', text)
        self.assertTrue(text.endswith('# END fragment-paths\n'), repr(text[-40:]))

    # F4 (#3593): a model module that has fragments in a Java file but no row in models.tsv is never run; that is RED.
    def test_module_without_a_models_row_is_red_and_named_with_its_file(self):
        self.java('m/A.java'); self.java('m/Newbie.java', FRAGMENT.replace('M:head', 'Newbie:head'))
        self.workflow('m/A.java', 'm/Newbie.java')
        rc, out = self.check()
        self.assertEqual(rc, 1, out)
        self.assertIn('RED module Newbie has tla fragments in m/Newbie.java but no row in', out)
        self.assertNotIn('RED module M ', out)

    def test_module_whose_only_fragments_are_tlacfg_still_needs_a_row(self):
        self.java('m/A.java'); self.java('m/Cfg.java', '/// ```tlacfg Cfg:ok\n/// INVARIANT X\n/// ```\nclass Cfg {}\n')
        self.workflow('m/A.java', 'm/Cfg.java')
        rc, out = self.check()
        self.assertEqual(rc, 1, out)
        self.assertIn('RED module Cfg ', out)

    def test_a_commented_out_models_row_is_not_a_row(self):
        self.model_rows('Other', extra='# M\tsrc\tok\tpass\t-\t-\tcommented out\n')
        self.java('m/A.java'); self.workflow('m/A.java')
        rc, out = self.check()
        self.assertEqual(rc, 1, out)
        self.assertIn('RED module M ', out)

    def test_one_module_across_two_files_needs_one_row(self):
        self.java('m/A.java'); self.java('m/B.java')
        self.workflow('m/A.java', 'm/B.java')
        rc, out = self.check()
        self.assertEqual(rc, 0, out)
        self.assertIn('1 modules, all with a row', out)

    def test_unreadable_models_file_is_an_error_not_a_pass(self):
        self.java('m/A.java'); self.workflow('m/A.java')
        os.remove(self.models)
        rc, out = self.check()
        self.assertEqual(rc, 2, out)

    def test_real_models_tsv_with_one_module_removed_is_red(self):
        with open(os.path.join(HERE, 'models.tsv')) as f:
            lines = f.read().split('\n')
        kept = [l for l in lines if not l.startswith('Stalled\t')]
        self.assertLess(len(kept), len(lines))
        with open(self.models, 'w') as f:
            f.write('\n'.join(kept))
        rc, out = run(['--check', '--base', REPO, '--workflow', REAL_WORKFLOW, '--models', self.models])
        self.assertEqual(rc, 1, out)
        self.assertIn('RED module Stalled has tla fragments in aether/aether-stream/', out)

    def test_real_repository_workflow_lists_every_fragment_file(self):
        rc, out = run(['--check', '--base', REPO, '--workflow', REAL_WORKFLOW])
        self.assertEqual(rc, 0, out)

    def test_real_workflow_with_one_entry_removed_is_red(self):
        with open(REAL_WORKFLOW) as f:
            lines = f.read().split('\n')
        idx = [i for i, l in enumerate(lines) if l.strip().startswith("- '") and l.strip().endswith('.java\'')]
        victim = lines.pop(idx[len(idx) // 2])
        with open(self.wf, 'w') as f:
            f.write('\n'.join(lines))
        rc, out = run(['--check', '--base', REPO, '--workflow', self.wf])
        self.assertEqual(rc, 1, out)
        self.assertIn('RED ' + victim.strip()[3:-1], out)


if __name__ == '__main__':
    unittest.main()
