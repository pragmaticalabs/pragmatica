#!/usr/bin/env python3
"""Assemble TLA+ fragments embedded in Java `///` doc comments into a TLA+ module and its TLC configs.

Convention (tools/tla/README.md):
  /// ```tla <Module>:<Part>        a TLA+ fragment. Part `head` and `tail` are the module skeleton; any other
  ///   ...                         Part is an action and must define an operator named Part at column 0.
  /// ```
  /// ```tlacfg <Module>:<Variant>  a TLC config, written to <Module>_<Variant>.cfg. Variant `common` is
  /// ```                           prepended to every other variant and is not written alone.

Assembly order is deterministic: head, then the action fragments in (source path, line) order, then tail.
The extractor writes the MODULE line and the closing ==== itself. Every assembled line is preceded by
the source position of its fragment, and <Module>.map.tsv maps each generated line to its source line, so a
TLC error position can be traced back to the Java file (`--locate`).

Exit status 2 with a `file:line: message` diagnostic on any convention violation.
"""
import argparse
import os
import re
import sys

OPEN = re.compile(r'^\s*///\s?```(tla|tlacfg)(?:\s+(.*?))?\s*$')
CLOSE = re.compile(r'^\s*///\s?```\s*$')
DOC = re.compile(r'^\s*///(?: ?)(.*)$')
TAG = re.compile(r'^([A-Za-z][A-Za-z0-9_]*):([A-Za-z][A-Za-z0-9_]*)$')


class Fail(Exception):
    pass


def scan(path, rel):
    """Yield (kind, module, part, rel, line, body_lines) for each fragment in one Java file."""
    with open(path, encoding='utf-8') as f:
        lines = f.read().split('\n')
    i = 0
    while i < len(lines):
        m = OPEN.match(lines[i])
        if not m:
            i += 1
            continue
        kind, tag = m.group(1), (m.group(2) or '')
        start = i + 1
        t = TAG.match(tag)
        if not t:
            raise Fail(f'{rel}:{start}: fragment tag "{tag}" is not <Module>:<Part>')
        body = []
        i += 1
        while True:
            if i >= len(lines):
                raise Fail(f'{rel}:{start}: fragment {tag} is not closed before end of file')
            if CLOSE.match(lines[i]):
                break
            o = OPEN.match(lines[i])
            if o:
                raise Fail(f'{rel}:{start}: fragment {tag} is not closed before fragment {o.group(2) or ""} opens (line {i + 1})')
            d = DOC.match(lines[i])
            if not d:
                raise Fail(f'{rel}:{start}: fragment {tag} is not closed before the doc comment ends (line {i + 1})')
            body.append((i + 1, d.group(1)))
            i += 1
        yield kind, t.group(1), t.group(2), rel, start, body
        i += 1


def collect(roots, base):
    frags = []
    files = []
    for root in roots:
        if os.path.isfile(root):
            files.append(root)
            continue
        for d, _, fs in os.walk(root):
            files += [os.path.join(d, f) for f in fs if f.endswith('.java')]
    for path in sorted(set(files), key=lambda p: os.path.relpath(p, base)):
        frags += list(scan(path, os.path.relpath(path, base)))
    return frags


def assemble(frags, module):
    mine = [f for f in frags if f[1] == module]
    if not mine:
        raise Fail(f'no fragment tagged {module}:<Part> found')
    parts, cfgs = {}, {}
    for kind, _, part, rel, line, body in mine:
        table = parts if kind == 'tla' else cfgs
        if part in table:
            prev = table[part]
            raise Fail(f'{rel}:{line}: duplicate {kind} fragment {module}:{part} (first at {prev[0]}:{prev[1]})')
        table[part] = (rel, line, body)
    for need in ('head', 'tail'):
        if need not in parts:
            raise Fail(f'missing skeleton fragment {module}:{need}')
    if not cfgs:
        raise Fail(f'no tlacfg fragment for {module}')
    tail_text = '\n'.join(text for _, text in parts['tail'][2])
    actions = sorted(((rel, line, part, body) for part, (rel, line, body) in parts.items()
                      if part not in ('head', 'tail')))
    for rel, line, part, body in actions:
        if not any(re.match(rf'^{re.escape(part)}\s*(\(.*\))?\s*==', text) for _, text in body):
            raise Fail(f'{rel}:{line}: action fragment {module}:{part} does not define an operator {part}')
        if not re.search(rf'\b{re.escape(part)}\b', tail_text):
            raise Fail(f'{rel}:{line}: action {part} is never referenced by {module}:tail (Next or fairness)')
    out, srcmap = [], []

    def emit(text, src):
        out.append(text)
        srcmap.append(src)

    emit(f'---------------------------- MODULE {module} ----------------------------', '-')
    emit(f'\\* GENERATED by tools/tla/extract.py from Java doc-comment fragments. Do not edit; edit the source.', '-')
    order = [('head',) + parts['head'][:2] + (parts['head'][2],)]
    order += [(part, rel, line, body) for rel, line, part, body in actions]
    order += [('tail',) + parts['tail'][:2] + (parts['tail'][2],)]
    for part, rel, line, body in order:
        emit('', '-')
        emit(f'\\* @fragment {module}:{part} from {rel}:{line}', f'{rel}:{line}')
        for src_line, text in body:
            emit(text, f'{rel}:{src_line}')
    emit('', '-')
    emit('=' * 77, '-')
    common = cfgs.pop('common', None)
    if not cfgs:
        raise Fail(f'only a common tlacfg fragment for {module}; add at least one variant')
    prefix = '\n'.join(text for _, text in common[2]) + '\n' if common else ''
    cfg_out = {v: prefix + '\n'.join(text for _, text in body) + '\n' for v, (rel, line, body) in cfgs.items()}
    return '\n'.join(out) + '\n', srcmap, cfg_out, [a[2] for a in actions]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--module', required=True)
    ap.add_argument('--out', required=True)
    ap.add_argument('--base', default='.')
    ap.add_argument('--locate', type=int, help='print the source position of a generated line and exit')
    ap.add_argument('roots', nargs='+')
    a = ap.parse_args()
    try:
        tla, srcmap, cfgs, actions = assemble(collect(a.roots, a.base), a.module)
    except Fail as e:
        print(f'extract: ERROR {e}', file=sys.stderr)
        sys.exit(2)
    if a.locate:
        print(srcmap[a.locate - 1])
        return
    os.makedirs(a.out, exist_ok=True)
    with open(os.path.join(a.out, f'{a.module}.tla'), 'w') as f:
        f.write(tla)
    with open(os.path.join(a.out, f'{a.module}.map.tsv'), 'w') as f:
        f.writelines(f'{n}\t{s}\n' for n, s in enumerate(srcmap, 1))
    for v, text in cfgs.items():
        with open(os.path.join(a.out, f'{a.module}_{v}.cfg'), 'w') as f:
            f.write(text)
    print(f'extract: {a.module}.tla {len(srcmap)} lines, actions={",".join(actions)}, cfgs={",".join(sorted(cfgs))}')


if __name__ == '__main__':
    main()
