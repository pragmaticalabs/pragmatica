#!/usr/bin/env python3
"""Generate aether/docs/reference/management-routes.md from the registered ManagementRoute enum (#3532).

The enum is the one source of truth for method, path and routing target; the minimum role comes from
ManagementRoutePermissions (GET -> VIEWER, listed operator routes -> OPERATOR, listed admin routes -> ADMIN,
anything unlisted -> ADMIN: the deny-by-default of permissionFor). Usage:

    python3 tools/gen-management-routes.py            # rewrite the reference page
    python3 tools/gen-management-routes.py --check    # exit 1 when the page differs from the enum (CI)
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ENUM = ROOT + '/aether/aether-management-api/src/main/java/org/pragmatica/aether/management/route/ManagementRoute.java'
PERMS = ROOT + '/aether/node/src/main/java/org/pragmatica/aether/api/ManagementRoutePermissions.java'
PAGE = ROOT + '/aether/docs/reference/management-routes.md'
API_BASE = '/api/v1'
ENTRY = re.compile(r'^    ([A-Z][A-Z0-9_]*)\(\s*(GET|POST|PUT|DELETE|PATCH)\b', re.M)


def strip_comments(text):
    return re.sub(r'//[^\n]*', '', text)


def split_args(body):
    """Top-level comma-separated arguments of the entry's constructor call (parentheses and strings balanced)."""
    depth, args, cur, in_str = 0, [], '', False
    for ch in body:
        if in_str:
            cur += ch
            in_str = ch != '"'
            continue
        if ch == '"':
            in_str = True
        elif ch == '(':
            depth += 1
            if depth == 1:
                continue
        elif ch == ')':
            depth -= 1
            if depth == 0:
                args.append(cur.strip())
                return args
        elif ch == ',' and depth == 1:
            args.append(cur.strip())
            cur = ''
            continue
        cur += ch
    raise SystemExit('unbalanced entry: ' + body[:60])


def parse_routes(enum_src):
    src = strip_comments(enum_src)
    src = src[:src.index('private static final String API_BASE')].rstrip() + '\n'
    starts = list(ENTRY.finditer(src))
    routes = []
    for i, m in enumerate(starts):
        end = starts[i + 1].start() if i + 1 < len(starts) else len(src)
        args = split_args(src[m.end(1):end])
        method = args[0]
        if args[1].startswith('List.of('):  # token form: (METHOD, List.of(spacer.., param..), target)
            path = API_BASE
            for kind, val in re.findall(r'(spacer|param)\("([^"]*)"\)', args[1]):
                path += '/' + (val if kind == 'spacer' else '{%s}' % val)
            target = args[2]
        else:  # literal form: (METHOD, "/x" | raw("/x"), List.of("p", ..), target)
            lit = re.fullmatch(r'(raw\()?"([^"]*)"\)?', args[1])
            if not lit:
                raise SystemExit('cannot parse ManagementRoute entry %s' % m.group(1))
            path = ('' if lit.group(1) else API_BASE) + lit.group(2)
            path += ''.join('/{%s}' % p for p in re.findall(r'"([^"]*)"', args[2]))
            target = args[3]
        routes.append((m.group(1), method, path, re.sub(r'^RouteTarget\.', '', ' '.join(target.split()))))
    return routes


def parse_roles(perm_src):
    roles = {}
    for label, fn in (('OPERATOR', 'operatorRoutes'), ('ADMIN', 'adminRoutes')):
        m = re.search(r'List<ManagementRoute> %s\(\) \{\s*return List\.of\((.*?)\);' % fn, perm_src, re.S)
        for name in re.findall(r'ManagementRoute\.([A-Z0-9_]+)', m.group(1)):
            roles[name] = label
    return roles


def render(routes, roles):
    lines = [
        '# Management API Route Table',
        '',
        '<!-- GENERATED by tools/gen-management-routes.py from ManagementRoute.java and ManagementRoutePermissions.java. Do not edit by hand; CI fails on drift. -->',
        '',
        'Every registered management route: %d entries. The narrative sections are in [management-api.md](management-api.md); '
        'this table is the complete, mechanically maintained inventory.' % len(routes),
        '',
        '- **Role** is the minimum authorization role: reads (`GET`) need `VIEWER`; a mutation needs the role named by '
        '`ManagementRoutePermissions`, and a mutation it does not list needs `ADMIN`.',
        '- **Served by** is the routing target: `LOCAL` answers on the node that received the request, `LEADER` forwards '
        'to the cluster leader, `ANY` is served from any core node, `taskGroup(X)` forwards to a node hosting that task group, '
        '`nodeIdParam(n)` forwards to the node named by path parameter n.',
        '- `{param}` segments are path parameters. Health probes and `/repository` routes are unversioned (no `/api/v1`).',
        '- Two routes, `WORKERS_HEALTH` and `WORKERS_ENDPOINTS`, are registered as honest `501 Not Implemented` stubs.',
        '',
        '| Route | Request | Role | Served by |',
        '|-------|---------|------|-----------|',
    ]
    for name, method, path, target in routes:
        role = 'VIEWER' if method == 'GET' else roles.get(name, 'ADMIN')
        lines.append('| `%s` | `%s %s` | %s | `%s` |' % (name, method, path, role, target))
    return '\n'.join(lines) + '\n'


def build():
    routes = parse_routes(open(ENUM).read())
    raw = len(re.findall(r'^    [A-Z][A-Z0-9_]*\(', strip_comments(open(ENUM).read()), re.M))
    if raw != len(routes):
        raise SystemExit('parsed %d routes but the enum has %d entry lines' % (len(routes), raw))
    roles = parse_roles(open(PERMS).read())
    unknown = sorted(set(roles) - {r[0] for r in routes})
    if unknown:
        raise SystemExit('ManagementRoutePermissions lists routes absent from the enum: %s' % unknown)
    return render(routes, roles)


if __name__ == '__main__':
    page = build()
    if '--check' in sys.argv:
        current = open(PAGE).read() if os.path.exists(PAGE) else ''
        if current != page:
            sys.stderr.write('%s is out of date: run python3 tools/gen-management-routes.py\n' % PAGE)
            sys.exit(1)
    else:
        open(PAGE, 'w').write(page)
