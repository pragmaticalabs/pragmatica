#!/usr/bin/env python3
"""Regenerate a shard weights file from one CI run's own surefire reports (#1643 Ember, #2414 Consensus).

  regen-shard-weights.py --module M --run RUN_ID               download RUN_ID's <M>-test-results-* artifacts with gh
  regen-shard-weights.py --module M --run RUN_ID --dir D       read reports already downloaded under D

A class's weight is its surefire suite times summed over every report file of the top-level class (TEST-x.C.xml and
TEST-x.C$Nested.xml alike), rounded up to whole seconds, and its line says which run measured it. A planned class the
run did not report keeps its previous line, marked as carried forward; a line for a class no longer in the source tree
is dropped. The planner (ember-shard.py) gives any class still missing its default weight.
"""
import argparse
import importlib.util
import math
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
from pathlib import Path

_spec = importlib.util.spec_from_file_location("ember_shard", Path(__file__).with_name("ember-shard.py"))
shard = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(shard)

HEADER = """# Measured wall seconds per {module} test class: surefire suite times summed per top-level class (@Nested included),
# rounded up. Generated by tools/regen-shard-weights.py --module {module} --run {run}; do not edit by hand.
# Used only to balance shards; a class missing here still runs, at the planner's default weight (75th percentile).
"""


def top_level_class(report):
    """TEST-org.x.EmberATest$Inner.xml -> EmberATest, the same mapping as the planner's --verify."""
    return report.name[len("TEST-"):-len(".xml")].rsplit(".", 1)[-1].split("$")[0]


def measured_seconds(report_dirs):
    """Unrounded seconds per top-level class, summed over every TEST-*.xml under the given directories."""
    seconds = {}
    for d in report_dirs:
        for report in sorted(Path(d).rglob("TEST-*.xml")):
            suite_time = float(ET.parse(report).getroot().get("time", "0").replace(",", ""))
            name = top_level_class(report)
            seconds[name] = seconds.get(name, 0.0) + suite_time
    return seconds


def previous_lines(path):
    """class -> its full line in the current weights file, so a class the run did not report keeps its provenance."""
    lines = {}
    for line in path.read_text().splitlines():
        body = line.split("#", 1)[0].strip()
        if body:
            lines[body.split()[0]] = line.strip()
    return lines


def regenerate(module, run, classes, measured, previous):
    """The new weights file's text, and the classes carried forward because the run did not report them."""
    out, carried = [HEADER.format(module=module, run=run)], []
    for c in sorted(classes):
        if c in measured:
            out.append(f"{c} {math.ceil(round(measured[c], 3))}  # measured at run {run}\n")
        elif c in previous:
            carried.append(c)
            line = previous[c]
            out.append(line + ("\n" if "#" in line else f"  # carried forward, not reported by run {run}\n"))
    return "".join(out), carried


def download(run, module, dest):
    subprocess.run(["gh", "run", "download", str(run), "-p", f"{module}-test-results-*", "-D", str(dest)], check=True)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--module", choices=sorted(shard.MODULES), required=True)
    ap.add_argument("--run", required=True, help="the CI run id the reports come from, recorded on every measured line")
    ap.add_argument("--dir", help="reports already downloaded (default: download the run's artifacts with gh)")
    args = ap.parse_args(argv)
    test_dir, weights_file, _ = shard.MODULES[args.module]
    with tempfile.TemporaryDirectory() as tmp:
        report_dir = Path(args.dir) if args.dir else Path(tmp)
        if not args.dir:
            download(args.run, args.module, report_dir)
        measured = measured_seconds([report_dir])
    if not measured:
        sys.exit(f"no TEST-*.xml under {report_dir}: refusing to rewrite {weights_file} from nothing")
    classes = shard.test_classes(test_dir)
    text, carried = regenerate(args.module, args.run, classes, measured, previous_lines(weights_file))
    weights_file.write_text(text)
    print(f"{weights_file}: {len([c for c in classes if c in measured])} class(es) measured at run {args.run}, "
          f"{len(carried)} carried forward{': ' + ', '.join(carried) if carried else ''}", file=sys.stderr)


if __name__ == "__main__":
    main()
